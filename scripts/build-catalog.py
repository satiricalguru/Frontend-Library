#!/usr/bin/env python3
"""Build every catalog page, the CSS palette file, SOURCES.md and data/sources.csv
from the JSON files in data/.  Run from the repo root:

    python3 scripts/build-catalog.py
"""
import csv
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
TRACK = []  # rows for data/sources.csv


def load(name):
    return json.loads((DATA / name).read_text())


def esc(s):
    return (s or "").replace("|", "\\|").replace("\n", " ").strip()


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def write(rel, text):
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text.rstrip() + "\n")
    return rel


def track(file, name, url, taken_from, collected):
    TRACK.append([file, name, url, taken_from, collected])


def header(title, emoji, blurb, source_url, collected, count, back="../../README.md"):
    return (
        f"<div align=\"center\">\n\n# {emoji} {title}\n\n{blurb}\n\n"
        f"<sub><b>{count:,}</b> entries · collected <b>{collected}</b> from "
        f"<a href=\"{source_url}\">{source_url}</a> · <a href=\"{back}\">← Back to library</a></sub>\n\n</div>\n\n"
    )


ATTR = (
    "> [!NOTE]\n> This is a **curated index of links**. Everything listed belongs to its original "
    "creators; open the link to view, license or buy it. The exact page every entry was taken from is "
    "logged in [SOURCES.md]({src}) and [data/sources.csv]({csv}).\n\n"
)

# --------------------------------------------------------------------------- Refero
def build_refero():
    d = load("refero-styles.json")
    items, col = d["items"], d["collected"]
    base = "styles/refero-design-systems"
    by = defaultdict(list)
    for s in items:
        by[s["category"] or "Other"].append(s)
    files = {}
    for cat, rows in sorted(by.items()):
        fn = f"{base}/{slug(cat)}.md"
        files[cat] = fn
        out = header(f"{cat} design systems", "🎨", f"Website styles in the **{cat}** category from Refero Styles — palette, typefaces and a link to the full DESIGN.md.", "https://styles.refero.design/", col, len(rows), "README.md")
        out += ATTR.format(src="../../SOURCES.md", csv="../../data/sources.csv")
        out += "| # | Brand | Theme | Key colors | Typefaces |\n|--:|:--|:--|:--|:--|\n"
        for i, s in enumerate(rows, 1):
            cols = " ".join(f"`{c['hex']}` {esc(c['name'])}" for c in s["colors"][:3]) or "—"
            theme = {"light": "☀️ light", "dark": "🌙 dark", "mixed": "🌓 mixed"}.get(s["theme"], "—")
            out += f"| {i} | [{esc(s['name'])}]({s['url']}) | {theme} | {cols} | {esc(', '.join(s['fonts'])) or '—'} |\n"
            track(fn, s["name"], s["url"], s["source"], col)
        write(fn, out)
    # index
    out = header("Refero design systems", "🎨", "AI-readable design systems (colors, typography, spacing, DESIGN.md) of real product websites, grouped by industry.", "https://styles.refero.design/", col, len(items))
    out += ATTR.format(src="../../SOURCES.md", csv="../../data/sources.csv")
    themes = Counter(s["theme"] for s in items)
    out += f"**Themes:** ☀️ {themes['light']} light · 🌙 {themes['dark']} dark · 🌓 {themes['mixed']} mixed\n\n"
    out += "| Category | Styles | Browse |\n|:--|--:|:--|\n"
    for cat, rows in sorted(by.items(), key=lambda kv: -len(kv[1])):
        out += f"| {cat} | {len(rows)} | [{Path(files[cat]).name}]({Path(files[cat]).name}) |\n"
    fonts = Counter(f for s in items for f in s["fonts"] if not re.search(r"system|apple|sans-serif|^serif$|monospace|Segoe|Blink", f, re.I))
    out += "\n## 🔤 Most-used typefaces across all styles\n\n| Typeface | Styles |\n|:--|--:|\n"
    for f, n in fonts.most_common(20):
        out += f"| {esc(f)} | {n} |\n"
    out += "\n## 🧪 Use the palettes\n\n[`palettes.css`](palettes.css) exposes every palette as CSS custom properties:\n\n```css\n@import \"styles/refero-design-systems/palettes.css\";\n.card { background: var(--linear-1); color: var(--linear-2); }\n```\n"
    write(f"{base}/README.md", out)
    # palettes.css
    css = "/* Brand palettes indexed from https://styles.refero.design/ (colors are facts about each\n   public website; names/brands belong to their owners). Generated by scripts/build-catalog.py */\n:root {\n"
    seen = set()
    for s in items:
        k = slug(s["name"])[:40] or "style"
        while k in seen:
            k += "-x"
        seen.add(k)
        for i, c in enumerate(s["colors"], 1):
            css += f"  --{k}-{i}: {c['hex']}; /* {c['name']} */\n"
    write(f"{base}/palettes.css", css + "}")
    return base + "/README.md", len(items), ["https://styles.refero.design/", "https://styles.refero.design/sitemaps/styles.xml"]


# --------------------------------------------------------------------------- Motion
def build_motion():
    d = load("motion-examples.json")
    items, col = d["items"], d["collected"]
    fn = "animations/motion-dev/README.md"
    ex = [x for x in items if x["kind"] == "example"]
    ui = [x for x in items if x["kind"] == "ui"]
    by = defaultdict(list)
    for x in ex:
        by[(x["categories"] or ["uncategorised"])[0]].append(x)
    plat = Counter(x["platform"] or "Other" for x in ex)
    out = header("Motion examples", "🌀", "Every public animation example and UI component from Motion (motion.dev) — React, JavaScript, Vue and Three.js, grouped by category.", "https://motion.dev/examples", col, len(items))
    out += ATTR.format(src="../../SOURCES.md", csv="../../data/sources.csv")
    out += "**Platforms:** " + " · ".join(f"{k} {v}" for k, v in plat.most_common()) + "\n\n"
    out += "**Jump to:** " + " · ".join(f"[{c.replace('-', ' ').title()}](#{slug(c.replace('-', ' '))})" for c in sorted(by)) + " · [Motion UI components](#motion-ui-components)\n\n"
    for c in sorted(by):
        out += f"## {c.replace('-', ' ').title()}\n\n| Example | Platform | What it does |\n|:--|:--|:--|\n"
        for x in sorted(by[c], key=lambda x: (x["name"].lower(), x["platform"])):
            out += f"| [{esc(x['name'])}]({x['url']}) | {x['platform'] or '—'} | {esc(x['description'])} |\n"
            track(fn, f"{x['name']} ({x['platform']})", x["url"], x["source"], col)
        out += "\n"
    out += "## Motion UI components\n\n| Component | What it does |\n|:--|:--|\n"
    for x in sorted(ui, key=lambda x: x["name"].lower()):
        out += f"| [{esc(x['name'])}]({x['url']}) | {esc(x['description'])} |\n"
        track(fn, x["name"], x["url"], x["source"], col)
    write(fn, out)
    return fn, len(items), ["https://motion.dev/examples", "https://motion.dev/examples?category=<name> (27 category pages)", "https://motion.dev/sitemap.xml"]


# --------------------------------------------------------------------------- Transitions
def build_transitions():
    d = load("transitions.json")
    items, col = d["items"], d["collected"]
    fn = "animations/transitions-dev/README.md"
    out = header("Transitions.dev library", "✨", "Production-ready UI micro-transitions (CSS + React, reduced-motion aware) from transitions.dev.", "https://transitions.dev/", col, len(items))
    out += ATTR.format(src="../../SOURCES.md", csv="../../data/sources.csv")
